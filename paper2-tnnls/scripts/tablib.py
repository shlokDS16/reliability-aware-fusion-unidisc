"""Helpers for the generated LaTeX tables: numbers are formatted here from run files, never typed; every row is preceded by `% run:` comments
naming the file and JSON key of each number in it. Output: complete `tabular` environments (booktabs) in paper2-tnnls/tables/.
Emphasis rule (all four tables): bold = the preregistered test of that row rejected its null at its preregistered level (Holm-adjusted where the
family is adjusted); nothing is underlined (there is no ranking of methods in any table)."""
from __future__ import annotations

import figstyle as S


def num(x: float, nd: int = 3, plus: bool = False) -> str:
    """Math-mode number with a true minus sign; positive numbers stay in text mode."""
    s = f"{x:.{nd}f}"
    if s.lstrip("-").strip("0.") == "":        # -0.000 prints as 0.000
        s = s.lstrip("-")
    if s.startswith("-"):
        return f"${s}$"
    return f"+{s}" if plus else s


def iv(lo: float, hi: float, nd: int = 3) -> str:
    def m(v):
        t = f"{v:.{nd}f}"
        if t.lstrip("-").strip("0.") == "":
            t = t.lstrip("-")
        return t
    return f"$[{m(lo)},\\,{m(hi)}]$"


def pv(p: float) -> str:
    if p >= 0.9995:
        return "1.00"
    if p < 0.001:
        return f"{p:.4f}"
    return f"{p:.3f}"


def bold(s: str) -> str:
    return f"\\textbf{{{s}}}"


def row(cells, runs: list[str]) -> str:
    """One table row, preceded by its `% run:` comment lines."""
    out = [f"% run: {r}" for r in runs]
    out.append(" & ".join(cells) + r" \\")
    return "\n".join(out)


def write(name: str, colspec: str, header: list[str], blocks: list[list[str]], preamble: list[str] | None = None, notes: list[str] | None = None,
          script: str | None = None) -> None:
    script = script or name.split('.')[0] + '.py'
    lines = [f"% {name}: generated by paper2-tnnls/scripts/{script} from committed runs/ files. Do not edit by hand."]
    lines += [f"% {p}" for p in (preamble or [])]
    lines += [f"\\begin{{tabular}}{{{colspec}}}", r"\toprule", " & ".join(header) + r" \\", r"\midrule"]
    for i, b in enumerate(blocks):
        if i:
            lines.append(r"\midrule")
        lines += b
    lines += [r"\bottomrule", r"\end{tabular}"]
    lines += [f"% {n}" for n in (notes or [])]
    (S.TABDIR / name).write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("wrote", S.TABDIR / name)
