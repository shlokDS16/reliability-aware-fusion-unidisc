"""Supplement S-VII tables of the exploratory Tier-3 ablation of Study 2 (writer W2, 2026-10-30).

Reads only runs/P2-LRF-ABL-SCORE/ablation_analysis.json (commit 4e785aa9) and writes four tabular files to paper2-tnnls/tables/:
  supp_ablation_vsLRF_L1.tex, supp_ablation_vsLRF_LG.tex  accuracy and net difference against the frozen LRF with its 95% interval
  supp_ablation_vsNONE.tex                                 net difference against NONE with its 95% interval, all eight cells
  supp_ablation_seeds.tex                                  seed-spread refits (three seeds, mean, SD, range)
Plan: research/paper2/tnnls/ABLATION-PLAN-2026-10-30.md sections 3, 4, 8. Rows in section-3 order (never sorted by result); nothing bold;
differences are variant minus reference (positive favours the variant). No p-value exists or is printed.
Run: python -I paper2-tnnls/scripts/tab_ablation.py  (CPU, stdlib only)
"""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / "runs" / "P2-LRF-ABL-SCORE" / "ablation_analysis.json"
REL = "runs/P2-LRF-ABL-SCORE/ablation_analysis.json"
OUT = ROOT / "paper2-tnnls" / "tables"

CELL_NAME = {
    "L1_clean": "clean", "L1_jpeg10": "JPEG 10", "L1_noise0.1": "noise 0.1", "L1_splice128": "splice 128",
    "LG_clean": "clean", "LG_shot_noise3": "shot", "LG_impulse_noise3": "impulse", "LG_speckle_noise3": "speckle",
}


def f(x: float, nd: int = 3) -> str:
    s = f"{x:.{nd}f}"
    if s.lstrip("-").strip("0.") == "":
        s = s.lstrip("-")
    return f"${s}$" if s.startswith("-") else s


def iv(c) -> str:
    return f"[{f(c[0])}, {f(c[1])}]"


def header(name: str) -> list[str]:
    return [f"% {name}: generated by paper2-tnnls/scripts/tab_ablation.py from {REL}. Do not edit by hand.",
            "% exploratory; added after the primary, family H and Study 2 results; differences are variant minus reference; nothing bold"]


def write(name: str, lines: list[str]) -> None:
    (OUT / name).write_text("\n".join(lines) + "\n", encoding="utf-8")


def main() -> None:
    d = json.loads(SRC.read_text(encoding="utf-8"))
    cells = d["meta"]["cell_order"]
    assert d["K"] == d["K_expected"] == 336
    rows = d["rows"]
    assert len(rows) == 21
    ref = d["references_accuracy"]
    n = d["n_per_cell"]

    # vs LRF, one table per fold block
    for tag, block in (("L1", cells[:4]), ("LG", cells[4:])):
        name = f"supp_ablation_vsLRF_{tag}.tex"
        L = header(name)
        L.append("\\begin{tabular}{@{}l" + "cc" * len(block) + "@{}}")
        L.append("\\toprule")
        L.append(" & " + " & ".join(f"\\multicolumn{{2}}{{c}}{{{CELL_NAME[c]} ($n={n[c]}$)}}" for c in block) + " \\\\")
        L.append("".join(f"\\cmidrule(lr){{{2 + 2 * i}-{3 + 2 * i}}}" for i in range(len(block))))
        L.append("Row & " + " & ".join("Acc. & $d$ vs LRF [95\\,\\%]" for _ in block) + " \\\\")
        L.append("\\midrule")
        for r in ("NONE", "LRF"):
            L.append(f"% run: {REL}:references_accuracy.{r}.{{{','.join(block)}}}; n_per_cell")
            L.append(f"{r} (reference) & " + " & ".join(f"{f(ref[r][c])} & --" for c in block) + " \\\\")
        L.append("\\midrule")
        prev_block = None
        for r in rows:
            if prev_block is not None and r["block"] != prev_block:
                L.append("\\midrule")
            prev_block = r["block"]
            L.append(f"% run: {REL}:rows[id={r['id']}].cells.{{{','.join(block)}}}.{{acc,vs_LRF.d,vs_LRF.ci95}}")
            L.append(r["id"] + " & " + " & ".join(f"{f(r['cells'][c]['acc'])} & {f(r['cells'][c]['vs_LRF']['d'])} {iv(r['cells'][c]['vs_LRF']['ci95'])}"
                                                    for c in block) + " \\\\")
        L += ["\\bottomrule", "\\end{tabular}"]
        write(name, L)

    # vs NONE, all eight cells, d [ci] only
    name = "supp_ablation_vsNONE.tex"
    L = header(name)
    L.append("\\begin{tabular}{@{}l" + "c" * len(cells) + "@{}}")
    L.append("\\toprule")
    L.append(" & \\multicolumn{4}{c}{L1 cells ($n=450$)} & \\multicolumn{4}{c}{LG cells ($n=300$)} \\\\")
    L.append("\\cmidrule(lr){2-5}\\cmidrule(lr){6-9}")
    L.append("Row & " + " & ".join(CELL_NAME[c] for c in cells) + " \\\\")
    L.append("\\midrule")
    prev_block = None
    for r in rows:
        if prev_block is not None and r["block"] != prev_block:
            L.append("\\midrule")
        prev_block = r["block"]
        L.append(f"% run: {REL}:rows[id={r['id']}].cells.*.vs_NONE.{{d,ci95}}")
        L.append(r["id"] + " & " + " & ".join(f"\\makecell{{{f(r['cells'][c]['vs_NONE']['d'])}\\\\{{}}{iv(r['cells'][c]['vs_NONE']['ci95'])}}}" for c in cells) + " \\\\")
    L += ["\\bottomrule", "\\end{tabular}"]
    write(name, L)

    # seed spread
    ss = d["seed_spread"]
    assert ss["seed0_is_prefixed"] is True
    name = "supp_ablation_seeds.tex"
    L = header(name)
    L.append(f"% max range over variants and cells: {ss['max_range_over_variants_and_cells']:.3f} ({REL}:seed_spread.max_range_over_variants_and_cells)")
    L.append("\\begin{tabular}{@{}l" + "c" * len(cells) + "@{}}")
    L.append("\\toprule")
    L.append(" & \\multicolumn{4}{c}{L1 cells ($n=450$)} & \\multicolumn{4}{c}{LG cells ($n=300$)} \\\\")
    L.append("\\cmidrule(lr){2-5}\\cmidrule(lr){6-9}")
    L.append("Refit & " + " & ".join(CELL_NAME[c] for c in cells) + " \\\\")
    L.append("\\midrule")
    for vid, cv in ss["rows"].items():
        L.append(f"% run: {REL}:seed_spread.rows.{vid}.*.{{acc_seed0_seed1_seed2,mean,sd_ddof1,range}}")
        label = "LRF refit (harness)" if vid == "LRF-H" else vid
        ents = []
        for c in cells:
            x = cv[c]
            a = x["acc_seed0_seed1_seed2"]
            ents.append(f"\\makecell{{{f(a[0])}, {f(a[1])}, {f(a[2])}\\\\{f(x['mean'])}, {f(x['sd_ddof1'])}, {f(x['range'])}}}")
        L.append(label + " & " + " & ".join(ents) + " \\\\")
    L += ["\\bottomrule", "\\end{tabular}"]
    write(name, L)
    print("ok")


if __name__ == "__main__":
    main()
