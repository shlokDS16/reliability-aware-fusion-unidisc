"""Does casting UniDisc's weights to bf16 change the per-position marginals relative to the checkpoint's own fp32 weights (+ bf16 autocast,
the demo's configuration)? 256px rows (L=331), batch 1, two masking levels. Writes smoke_unidisc/precision_check_256px.json.
fp32 weights need 5.6 GB of GPU memory (and as much system commit), hence the sequential build."""
import gc, json, sys
from common import *  # noqa
import unidisc_smoke as S
import unidisc_setup as U
import torch

RES = 256


def states(model, cfg):
    """Prompt-only row, and the row with 50% of the masked positions revealed from a quick 20-step sample."""
    st = S.build_state(model, cfg, RES, joint=True)
    torch.manual_seed(0)
    import numpy as np; np.random.seed(0)
    rec = {}
    orig = model.decode_sampling
    model.decode_sampling = lambda x, *a, **k: (rec.__setitem__("x", x.clone()), ([], []))[1]
    model._sample(text_only=False, num_steps=20, batch_size_per_gpu=1, example_batch=dict(input_ids=st["x0"], attention_mask=st["attention_mask"]), sample_batch_idx=0,
                  modality=st["modality"], sample_ids=st["sample_ids"], allow_interleaved_conditional=True, x0_unmask=st["unmask"], x0=st["x0"])
    model.decode_sampling = orig
    full = rec["x"]
    g = torch.Generator(device="cuda").manual_seed(1)
    reveal = (torch.rand(full.shape, device="cuda", generator=g) < 0.5) & (~st["unmask"])
    half = torch.where(reveal, full, S.prior(model, st))
    return st, dict(prompt_only=S.prior(model, st), half_revealed=half), full


def run(bf16, xs_given=None):
    cfg = U.make_config(["eval.visualize_sample=false", "sampling.steps=20", "sampling.max_sampling_steps=20"])
    S.patch_attention()
    model, cfg = U.build_model(cfg, bf16=bf16)
    st, xs, full = states(model, cfg)
    if xs_given is not None:   # identical masked states for both weight precisions
        xs = {k: v.cuda() for k, v in xs_given.items()}; full = xs['half_revealed']
    out = {}
    for name, x in xs.items():
        with torch.no_grad():
            lp = S.marginals_raw(model, x, st, return_log=True).float().cpu()
        out[name] = lp
    info = dict(weights_dtype=str(next(model.backbone.parameters()).dtype), vram_gb=torch.cuda.memory_allocated() / 1e9)
    meta = dict(xs={k: v.cpu() for k, v in xs.items()}, masks={k: (v == model.mask_index)[0].cpu() for k, v in xs.items()}, modality=st["modality"].cpu(), full=full.cpu())
    del model; gc.collect(); torch.cuda.empty_cache()
    return out, info, meta


def main():
    wait_commit(8.0)
    a, ia, meta = run(bf16=True)
    wait_commit(9.0)
    b, ib, _ = run(bf16=False, xs_given=meta['xs'])
    res = dict(bf16_weights=ia, fp32_weights=ib, resolution=RES, seq_len=int(meta["full"].shape[1]),
               note="both precisions evaluated on the SAME token states (generated by the bf16 model with a 20-step sample; half_revealed = 50% of the masked positions revealed from it)")
    for name in a:
        pa, pb = a[name].exp(), b[name].exp()
        mk = meta['masks'][name]
        pa_m, pb_m = pa[0][mk], pb[0][mk]
        ent = lambda p: -(p * p.clamp_min(1e-30).log()).sum(-1)
        res[name] = dict(n_positions=int(mk.sum()), top1_agreement=float((pa_m.argmax(-1) == pb_m.argmax(-1)).float().mean()),
                         max_abs_prob_diff=float((pa_m - pb_m).abs().max()), mean_abs_entropy_diff_nats=float((ent(pa_m) - ent(pb_m)).abs().mean()),
                         mean_entropy_bf16=float(ent(pa_m).mean()), mean_entropy_fp32=float(ent(pb_m).mean()),
                         tv_distance_mean=float(0.5 * (pa_m - pb_m).abs().sum(-1).mean()))
    (U.OUT / "smoke_unidisc" / "precision_check_256px.json").write_text(json.dumps(res, indent=2))
    print(json.dumps(res, indent=2))


if __name__ == "__main__":
    main()
