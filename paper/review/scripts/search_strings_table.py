import re
"""Supplement S1: every logged search, read from research/review/corpus/search-log.jsonl.

Writes paper/review/tables/search-strings.tex: one entry per distinct (database, query) with string label, run time
(UTC), records retrieved and the exact query text; OpenReview runs (one per term and venue group) are listed as
term x group with their counts, since their query is 'term=<phrase>&source=forum&group=<venue>' and the second
clause of the string is applied locally (filters field of the log). Nothing is typed by hand.

    python paper/review/scripts/search_strings_table.py
"""
import collections
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
rows = [json.loads(l) for l in open(ROOT / "research/review/corpus/search-log.jsonl", encoding="utf-8") if l.strip()]


def tex(s):
    rep = {"\\": r"\textbackslash{}", "&": r"\&", "%": r"\%", "$": r"\$", "#": r"\#", "_": r"\_", "{": r"\{",
           "}": r"\}", "~": r"\textasciitilde{}", "^": r"\textasciicircum{}"}
    return "".join(rep.get(c, c) for c in str(s))


def when(r):
    t = str(r.get("executed_utc", ""))
    return f"{t[:4]}-{t[4:6]}-{t[6:8]} {t[9:11]}:{t[11:13]}" if len(t) >= 13 else tex(t)


L = [r"% generated by paper/review/scripts/search_strings_table.py from research/review/corpus/search-log.jsonl; do not edit",
     r"\begin{small}"]
other = [r for r in rows if not r.get("database", "").startswith("OpenReview")]
orv = [r for r in rows if r.get("database", "").startswith("OpenReview")]
seen = set()
db_order = []
for r in other:
    if r["database"] not in db_order:
        db_order.append(r["database"])
for db in db_order:
    L.append(r"\paragraph{" + tex(db) + "}")
    for r in other:
        if r["database"] != db:
            continue
        key = (db, r.get("query"), r.get("executed_utc"))
        if key in seen:
            continue
        seen.add(key)
        L.append(r"\noindent\textbf{" + tex(r.get("string", "")) + "}, " + when(r) + " UTC, "
                 + f"{r.get('records_retrieved', 'n/a')} records"
                 + (f" (hits reported {r['hits_reported']})" if r.get("hits_reported") not in (None, r.get("records_retrieved")) else "")
                 + r".\\" + "\n" + r"{\ttfamily\footnotesize " + tex(r.get("query", "")) + r"}\par\smallskip")
L.append(r"\paragraph{OpenReview API v2 (api2.openreview.net/notes/search)}")
L.append(tex(orv[0].get("filters", "")) + r". Query form: \texttt{term=<phrase>\&source=forum\&group=<venue group>}. "
         + f"{len(orv)} runs, {sum(r.get('records_retrieved') or 0 for r in orv)} records before deduplication:")
by = collections.OrderedDict()
for r in orv:
    q = r["query"]
    grp = q.split("group=")[-1] if "group=" in q else "?"
    by.setdefault(r["string"], []).append(f"{tex(grp)} {r.get('records_retrieved')}")
L.append(r"\begin{itemize}\setlength\itemsep{0pt}")
for k, v in by.items():
    L.append(r"\item \texttt{" + tex(k) + "}: " + "; ".join(v))
L.append(r"\end{itemize}")
L.append(r"\end{small}")
def _nopath(s):
    if s.startswith("%"):
        return s
    s = re.sub(r", ingest tools/ingest\\_subscription\.py", "", s)
    s = re.sub(r"(research|tools|analysis)/[A-Za-z0-9_\\\-./]+", "the archived search log", s)
    s = re.sub(r",?\s*D00\d\d combined query", ", combined query", s)
    return re.sub(r"  +", " ", s)


L = [_nopath(x) for x in L]
out = ROOT / "paper/review/tables/search-strings.tex"
out.write_text("\n".join(L) + "\n", encoding="utf-8")
print(out, "entries", len(seen), "openreview runs", len(orv))
