"""Quality-appraisal tables (RQ6) from the D0052 extraction sample.

Decision D0060: the primary column is the included studies (update strata); the seed stratum is a separate column;
intervals are the stratified bootstrap of rq_analysis.py. Writes paper/review/tables/qa-summary.tex (main text: per item
QA1-QA9, the number of included sampled studies at score 0, 1 and 2, the weighted share at 2 with its 95 percent
interval at the low and the high reading, the seed stratum's share at 2, NA counts), paper/review/tables/sensitivity.tex
(supplement S6: verdict inputs and QA items in five columns: included, seed, combined, included without rejected
records, included with extractor B on the eight double-read studies; and the verdicts) and
paper/review/tables/qa-per-study.tex (supplement S6: one row per sampled study, its stratum, a short title, and the
nine scores, shown as one number when the low and high readings agree and as low/high when they differ).
Inputs: analysis/extraction/d0052/rq-results.json (D0060) and qa-table.jsonl, both from rq_analysis.py; titles from
research/review/corpus/screening-queue-final-2026-10-15.jsonl, screening-queue-2026-10-15.jsonl,
analysis/screening/ta-recheck-candidates-v1.2.jsonl, and for the seed stratum the second line of the census text. Nothing is typed by hand.

    python paper/review/scripts/qa_tables.py
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
D = ROOT / "analysis/extraction/d0052"
OUT = ROOT / "paper/review/tables"
RES = json.load(open(D / "rq-results.json", encoding="utf-8"))
rows = [json.loads(l) for l in open(D / "qa-table.jsonl", encoding="utf-8") if l.strip()]
rows = [x for x in rows if x["id"] not in RES["left_frame_D0059"]]          # same frame as the weighted estimates
seed = json.load(open(D / "seed-sample.json", encoding="utf-8"))
# landmark tranche (D0061): own column and own per-study rows (analysis/extraction/lmk/qa-table-landmark.jsonl)
LMKQ = ROOT / "analysis/extraction/lmk/qa-table-landmark.jsonl"
lrows = [json.loads(l) for l in open(LMKQ, encoding="utf-8") if l.strip()] if LMKQ.exists() else []
LMK_N = RES["D0060"].get("landmark_meta", {}).get("n_extracted", 0)
NAMES = {"QA1": "Code released", "QA2": "Weights and data released", "QA3": "Protocol reported",
         "QA4": "Repeated runs (main comparison)", "QA5": "Uncertainty (main comparison)",
         "QA6": "Budgets of both arms", "QA7": "Ablation of the credited component", "QA8": "Claims match tables",
         "QA9": "Limitations and failure cases"}


def tex(s):
    rep = {"\\": r"\textbackslash{}", "&": r"\&", "%": r"\%", "$": r"\$", "#": r"\#", "_": r"\_", "{": r"\{",
           "}": r"\}", "~": r"\textasciitilde{}", "^": r"\textasciicircum{}"}
    return "".join(rep.get(c, c) for c in str(s))


titles = {}
for f in ("screening-queue-final-2026-10-15.jsonl", "screening-queue-2026-10-15.jsonl"):
    for l in open(ROOT / "research/review/corpus" / f, encoding="utf-8"):
        r = json.loads(l)
        titles.setdefault(r.get("id"), r.get("title") or "")
for l in open(ROOT / "analysis/screening/ta-recheck-candidates-v1.2.jsonl", encoding="utf-8"):
    r = json.loads(l)
    if r.get("title"):
        titles.setdefault(r.get("id"), r["title"])
for l in open(ROOT / "analysis/screening/landmark/landmark-frame.jsonl", encoding="utf-8"):
    r = json.loads(l)
    if r.get("tranche_record") and r.get("title"):
        titles.setdefault(r["tranche_record"], r["title"])
for i, p in seed["provenance"].items():
    t = ROOT / "research/sources/md/census-text-paged" / f"{i}.txt"
    lines = [x.strip() for x in t.read_text(encoding="utf-8", errors="replace").splitlines()[1:4] if x.strip()]
    titles[i] = lines[0] if lines else ""


def short(t, n=58):
    t = " ".join(str(t).split())
    return t if len(t) <= n else t[: n - 1].rsplit(" ", 1)[0] + "..."


def cell(e):
    if not e or e.get("share") is None:
        return "--"
    ci = e.get("ci95")
    return f"{e['share']:.2f}" + (f" [{ci[0]:.2f}, {ci[1]:.2f}]" if ci else "")


P = RES["D0060"]
INC, SEEDC = P["included"], P["seed"]
SHORT = {**NAMES, "QA2": "Weights and data", "QA4": "Repeated runs", "QA5": "Uncertainty", "QA7": "Credited ablation",
         "QA9": "Limitations stated"}   # main-text table only (definitions in Section 2)
lk = lambda e: "--" if not e or e.get("share") is None else f"{e['count']}/{e['of']}"   # landmark: one stratum, k/n
L = [r"% generated by paper/review/scripts/qa_tables.py from analysis/extraction/d0052/rq-results.json (D0060); do not edit",
     r"\setlength{\tabcolsep}{4pt}", r"\begin{tabular}{@{}l r r r l l l r r@{}}", r"\toprule",
     r" & \multicolumn{5}{c}{Included studies (59 sampled)} & Seed (20) & Landmark & \\",
     r"\cmidrule(lr){2-6}\cmidrule(lr){7-7}\cmidrule(lr){8-8}",
     r"Item & 0 & 1 & 2 & At 2, low & At 2, high & At 2, low & At 2, low & NA \\", r"\midrule"]
for k in [f"QA{j}" for j in range(1, 10)]:
    c = lambda s_: INC[f"{k}_low_eq{s_}"]["count"]
    na = sum(1 for x in rows if x["stratum"] != "S-seed" and x["low"][k] == "NA")
    L.append(f"{k} {tex(SHORT[k])} & {c(0)} & {c(1)} & {c(2)} & {cell(INC[f'{k}_low_eq2'])} & "
             f"{cell(INC[f'{k}_high_eq2'])} & {cell(SEEDC[f'{k}_low_eq2'])} & {lk(P.get('landmark', {}).get(f'{k}_low_eq2'))} & {na} \\\\")
L += [r"\bottomrule", r"\end{tabular}"]
(OUT / "qa-summary.tex").write_text("\n".join(L) + "\n", encoding="utf-8")

P = [r"% generated by paper/review/scripts/qa_tables.py from analysis/extraction/d0052/qa-table.jsonl; do not edit",
     r"\begin{small}", r"\setlength{\tabcolsep}{3.5pt}", r"\begin{longtable}{@{}l l p{4.0cm} *{9}{c}@{}}", r"\toprule",
     r"Id & Stratum & Study & QA1 & QA2 & QA3 & QA4 & QA5 & QA6 & QA7 & QA8 & QA9 \\", r"\midrule", r"\endhead"]
# citation keys of the sampled studies, verified against the record titles by scripts/s6_bib.py (tables/s6-keys.json)
_kf = OUT / "s6-keys.json"
S6KEYS = {i: v["key"] for i, v in json.loads(_kf.read_text(encoding="utf-8"))["keys"].items() if v.get("key")} if _kf.exists() else {}
for x in sorted(rows, key=lambda x: (x["stratum"], x["id"])) + lrows:
    sc = []
    for k in [f"QA{j}" for j in range(1, 10)]:
        lo, hi = x["low"][k], x["high"][k]
        sc.append(str(lo) if lo == hi else f"{lo}/{hi}")
    cite = f"~\\cite{{{S6KEYS[x['id']]}}}" if x["id"] in S6KEYS else ""
    P.append(f"{x['id']} & {x['stratum']} & {tex(short(titles.get(x['id'], '')))}{cite} & " + " & ".join(sc) + r" \\")
P += [r"\bottomrule", r"\end{longtable}", r"\end{small}"]
(OUT / "qa-per-study.tex").write_text("\n".join(P) + "\n", encoding="utf-8")
missing = [x["id"] for x in rows + lrows if not titles.get(x["id"])]
print(f"qa-summary.tex 9 items; qa-per-study.tex {len(rows) + len(lrows)} rows ({len(lrows)} landmark); titles missing {missing}")

# ---- sensitivity of the verdict inputs (D0060): supplement S6
P = RES["D0060"]
LAB = [("RQ2_has_ar", "RQ2: diffusion--autoregressive comparison"), ("RQ2_matched_any", "RQ2: matched budget in at least one (of those)"),
       ("RQ2_budget_not_reported_any", "RQ2: a budget not reported (of those)"), ("RQ2_variance_any", "RQ2: variation reported (of those)"),
       ("RQ2_better_majority", "RQ2: diffusion better on most units (signed)"), ("RQ2_worse_majority", "RQ2: diffusion worse on most units (signed)"),
       ("RQ3_has_training", "RQ3: training contrast"), ("RQ3_held_fixed_all", "RQ3: held-fixed factors stated (of those)"),
       ("RQ3_credited_ablation_any", "RQ3: credited component ablated (of those)"), ("RQ3_variance_any", "RQ3: variation reported (of those)"),
       ("RQ3_anchor_better_majority", "RQ3: anchor better on most units (signed)"),
       ("RQ4_has_inference", "RQ4: inference contrast"), ("RQ4_budget_reported_any", "RQ4: budget reported (of those)"),
       ("RQ4_variance_any", "RQ4: variation reported (of those)"), ("RQ4_sweep_up_majority", "RQ4: most sweep curves improve (sweeps)"),
       ("RQ4_sweep_all_up", "RQ4: every sweep curve improves (sweeps)"), ("RQ4_any_nonmonotone", "RQ4: a non-monotone curve (sweeps)"),
       ("RQ4_any_nonmonotone_tol1pct", r"RQ4: same, changes under 1\% ignored"),
       ("RQ5_has_ablation", "RQ5: synergy ablation (unified)"), ("RQ5_joint_better_majority", "RQ5: joint arm better on most units (signed)"),
       ("RQ5_joint_worse_majority", "RQ5: joint arm worse on most units (signed)"),
       ("claims_any_unsupported", "A claim unsupported by the paper's tables")] + \
      [(f"QA{j}_low_eq2", f"QA{j} at score 2 (low reading)") for j in range(1, 10)]
V = [("included", "Included"), ("seed", "Seed"), ("combined", "Combined"), ("included_without_rejected", "Incl., no rejected"),
     ("included_EB_on_8", "Incl., extractor B on 8")]


def sv(e):
    return "--" if not e or e.get("share") is None else f"{e['count']}/{e['of']} {e['share']:.2f}"


T = [r"% generated by paper/review/scripts/qa_tables.py from rq-results.json D0060; do not edit",
     r"\begingroup\setlength{\tabcolsep}{4pt}", r"\begin{longtable}{@{}p{4.6cm} " + "l " * len(V) + r"@{}}", r"\toprule",
     r"\caption{Inputs of the RQ2--RQ5 verdicts and the appraisal items in five columns (count of studies, weighted share); last rows: verdicts (U untested, M mixed, W weakly supported, S well supported), then the included-study verdicts with one threshold changed at a time.}\label{tab:s-sens}\\",
     "Estimate & " + " & ".join(n for _, n in V) + r" \\", r"\midrule", r"\endhead"]
for k, name in LAB:
    T.append(name + " & " + " & ".join(sv(P[v].get(k)) for v, _ in V) + r" \\")
T.append(r"\midrule")
T.append(r"Verdict RQ2 / RQ3 / RQ4 / RQ5 & " + " & ".join(
    " / ".join({"untested": "U", "mixed": "M", "weakly supported": "W", "well supported": "S"}[P["verdicts"][v][rq]["verdict"]]
               for rq in ("RQ2", "RQ3", "RQ4", "RQ5")) for v, _ in V) + r" \\")
# threshold sensitivity of the verdicts (included column only; one D0060 threshold changed at a time)
VS = P["verdicts_threshold_sensitivity"]
TN = {"direction_share": "direction share", "control_share": "control share", "min_signed": "minimum signed studies"}
VA = {"untested": "U", "mixed": "M", "weakly supported": "W", "well supported": "S"}
T.append(r"\midrule")
T.append(r"\multicolumn{%d}{@{}p{0.95\linewidth}}{\emph{Verdicts on the included studies under other thresholds (defaults: direction share 2/3, control share 0.5, minimum 5 signed studies)}} \\" % (len(V) + 1))
for x in VS["variants"]:
    val = f"{x['value']:.2f}" if isinstance(x["value"], float) else str(x["value"])
    T.append(f"Verdict RQ2 / RQ3 / RQ4 / RQ5, {TN[x['threshold']]} {val} & "
             + " / ".join(VA[x["verdicts"][rq]] for rq in ("RQ2", "RQ3", "RQ4", "RQ5"))
             + " & " * (len(V) - 1) + r" \\")
T += [r"\bottomrule", r"\end{longtable}", r"\endgroup"]
(OUT / "sensitivity.tex").write_text("\n".join(T) + "\n", encoding="utf-8")
print("sensitivity.tex", len(LAB), "rows")

# ---- landmark tranche (D0061, D0063): the same inputs in its own table, beside the included column for reference
if "landmark" in P:
    VL = [("included", "Included"), ("landmark", "Landmark"), ("landmark_without_rejected", "Landmark, no rejected")]
    m = P["landmark_meta"]
    T = [r"% generated by paper/review/scripts/qa_tables.py from rq-results.json D0060 (landmark, landmark_meta); do not edit",
         r"\begin{longtable}{@{}p{6.2cm} " + "l " * len(VL) + r"@{}}", r"\toprule",
         r"\caption{The inputs of Table~\ref{tab:s-sens} for the landmark set: %d extracted of its %d included studies, a seeded random prefix, with and without the %d records the validator still rejected; the included column is repeated for reference. QA1 for the landmark studies uses the text-only part of the rule.}\label{tab:s-sens-landmark}\\"
         % (m["n_extracted"], m["N_includes"], len(m["rejected_at_final_pass"])),
         "Estimate & " + " & ".join(n for _, n in VL) + r" \\", r"\midrule", r"\endhead"]
    for k, name in LAB:
        # landmark columns: one stratum, so the share is count/of exactly (no second rounding of a rounded share)
        svl = lambda e: "--" if not e or e.get("share") is None else f"{e['count']}/{e['of']} {e['count'] / e['of']:.2f}"
        T.append(name + " & " + " & ".join((sv if v == "included" else svl)(P[v].get(k)) for v, _ in VL) + r" \\")
    T.append(r"\midrule")
    T.append(r"Verdict RQ2 / RQ3 / RQ4 / RQ5 & " + " & ".join(
        " / ".join(VA[P["verdicts"][v][rq]["verdict"]] for rq in ("RQ2", "RQ3", "RQ4", "RQ5")) for v, _ in VL) + r" \\")
    T += [r"\bottomrule", r"\end{longtable}"]
    (OUT / "sensitivity-landmark.tex").write_text("\n".join(T) + "\n", encoding="utf-8")
    print("sensitivity-landmark.tex", len(LAB), "rows")
