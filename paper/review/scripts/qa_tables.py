"""Quality-appraisal tables (RQ6) from the D0052 extraction sample.

Writes paper/review/tables/qa-summary.tex (main text: per item QA1-QA9, the number of sampled studies at score 0, 1 and
2 and the stratum-weighted share at 2 with its 95 percent interval, at the low and the high reading; NA counts) and
paper/review/tables/qa-per-study.tex (supplement S6: one row per sampled study, its stratum, a short title, and the
nine scores, shown as one number when the low and high readings agree and as low/high when they differ).
Inputs: analysis/extraction/d0052/rq-results.json (RQ6) and qa-table.jsonl, both from rq_analysis.py; titles from
research/review/corpus/screening-queue-final-2026-10-15.jsonl, screening-queue-2026-10-15.jsonl,
analysis/screening/ta-recheck-candidates-v1.2.jsonl, and for the seed stratum the second line of the census text. Nothing is typed by hand.

    python paper/review/scripts/qa_tables.py
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
D = ROOT / "analysis/extraction/d0052"
OUT = ROOT / "paper/review/tables"
RES = json.load(open(D / "rq-results.json", encoding="utf-8"))
R = RES["RQ6"]
rows = [json.loads(l) for l in open(D / "qa-table.jsonl", encoding="utf-8") if l.strip()]
rows = [x for x in rows if x["id"] not in RES["left_frame_D0059"]]          # same frame as the weighted estimates
seed = json.load(open(D / "seed-sample.json", encoding="utf-8"))
NAMES = {"QA1": "Code released", "QA2": "Weights and data released", "QA3": "Protocol reported",
         "QA4": "Repeated runs (main comparison)", "QA5": "Uncertainty (main comparison)",
         "QA6": "Budgets of both arms", "QA7": "Ablation of the credited component", "QA8": "Claims match tables",
         "QA9": "Limitations and failure cases"}


def tex(s):
    rep = {"\\": r"\textbackslash{}", "&": r"\&", "%": r"\%", "$": r"\$", "#": r"\#", "_": r"\_", "{": r"\{",
           "}": r"\}", "~": r"\textasciitilde{}", "^": r"\textasciicircum{}"}
    return "".join(rep.get(c, c) for c in str(s))


titles = {}
for f in ("screening-queue-final-2026-10-15.jsonl", "screening-queue-2026-10-15.jsonl"):
    for l in open(ROOT / "research/review/corpus" / f, encoding="utf-8"):
        r = json.loads(l)
        titles.setdefault(r.get("id"), r.get("title") or "")
for l in open(ROOT / "analysis/screening/ta-recheck-candidates-v1.2.jsonl", encoding="utf-8"):
    r = json.loads(l)
    if r.get("title"):
        titles.setdefault(r.get("id"), r["title"])
for i, p in seed["provenance"].items():
    t = ROOT / "research/sources/md/census-text-paged" / f"{i}.txt"
    lines = [x.strip() for x in t.read_text(encoding="utf-8", errors="replace").splitlines()[1:4] if x.strip()]
    titles[i] = lines[0] if lines else ""


def short(t, n=58):
    t = " ".join(str(t).split())
    return t if len(t) <= n else t[: n - 1].rsplit(" ", 1)[0] + "..."


def cell(e):
    if not e or e.get("share") is None:
        return "--"
    ci = e.get("ci95")
    return f"{e['share']:.2f}" + (f" [{ci[0]:.2f}, {ci[1]:.2f}]" if ci else "")


L = [r"% generated by paper/review/scripts/qa_tables.py from analysis/extraction/d0052/rq-results.json; do not edit",
     r"\begin{tabular}{@{}l r r r l r r r l r@{}}", r"\toprule",
     r" & \multicolumn{4}{c}{Low reading (unclear = no)} & \multicolumn{4}{c}{High reading (unclear = yes)} & \\",
     r"\cmidrule(lr){2-5}\cmidrule(lr){6-9}",
     r"Item & 0 & 1 & 2 & Weighted share at 2 & 0 & 1 & 2 & Weighted share at 2 & NA \\", r"\midrule"]
for k in [f"QA{j}" for j in range(1, 10)]:
    q = R[k]
    lo, hi = q["low"], q["high"]
    c = lambda d, s: d[str(s)]["count"] if str(s) in d else d[s]["count"]
    L.append(f"{k} {tex(NAMES[k])} & {c(lo, 0)} & {c(lo, 1)} & {c(lo, 2)} & {cell(lo.get('2') or lo.get(2))} & "
             f"{c(hi, 0)} & {c(hi, 1)} & {c(hi, 2)} & {cell(hi.get('2') or hi.get(2))} & {q['NA']} \\\\")
L += [r"\bottomrule", r"\end{tabular}"]
(OUT / "qa-summary.tex").write_text("\n".join(L) + "\n", encoding="utf-8")

P = [r"% generated by paper/review/scripts/qa_tables.py from analysis/extraction/d0052/qa-table.jsonl; do not edit",
     r"\begin{small}", r"\begin{longtable}{@{}l l p{5.6cm} *{9}{c}@{}}", r"\toprule",
     r"Id & Stratum & Study & QA1 & QA2 & QA3 & QA4 & QA5 & QA6 & QA7 & QA8 & QA9 \\", r"\midrule", r"\endhead"]
for x in sorted(rows, key=lambda x: (x["stratum"], x["id"])):
    sc = []
    for k in [f"QA{j}" for j in range(1, 10)]:
        lo, hi = x["low"][k], x["high"][k]
        sc.append(str(lo) if lo == hi else f"{lo}/{hi}")
    P.append(f"{x['id']} & {x['stratum']} & {tex(short(titles.get(x['id'], '')))} & " + " & ".join(sc) + r" \\")
P += [r"\bottomrule", r"\end{longtable}", r"\end{small}"]
(OUT / "qa-per-study.tex").write_text("\n".join(P) + "\n", encoding="utf-8")
missing = [x["id"] for x in rows if not titles.get(x["id"])]
print(f"qa-summary.tex 9 items; qa-per-study.tex {len(rows)} rows; titles missing {missing}")

# ---- sensitivity of the headline estimates (rq_analysis.py "sensitivity"): supplement S6
S = RES["sensitivity"]
LAB = {"census_nonplain_or_unstated": "Census: value rule non-plain or unstated",
       "RQ2_has_ar_group": "RQ2: has a diffusion--autoregressive comparison",
       "RQ2_ar_budget_not_reported_any": "RQ2: a budget not reported (of those)",
       "RQ2_ar_numbers_copied_any": "RQ2: autoregressive numbers copied (of those)",
       "RQ2_ar_variance_any": "RQ2: variation reported (of those)",
       "RQ3_credited_ablation_any": "RQ3: credited component ablated",
       "RQ3_held_fixed_stated_all": "RQ3: held-fixed factors stated",
       "RQ3_variance_any": "RQ3: variation reported",
       "RQ4_has_inference_group": "RQ4: has an inference contrast",
       "RQ4_budget_reported_any": "RQ4: budget reported (of those)",
       "RQ4_variance_any": "RQ4: variation reported (of those)",
       "RQ4_any_nonmonotone_dose_curve": "RQ4: a non-monotone sweep (of studies with a sweep)"}
V = [("S0_main", "Main"), ("S1_update_strata_only", "No seed stratum"), ("S2_without_rejected", "Without rejected records"),
     ("S3_second_reader_ids_from_EB", "Extractor B on the 8")]


def sv(e):
    return "--" if not e or e.get("share") is None else f"{e['count']}/{e['of']}, {e['share']:.2f}"


T = [r"% generated by paper/review/scripts/qa_tables.py from rq-results.json sensitivity; do not edit",
     r"\begin{tabular}{@{}l " + "r " * len(V) + r"@{}}", r"\toprule",
     "Estimate & " + " & ".join(n for _, n in V) + r" \\", r"\midrule"]
for k, name in LAB.items():
    T.append(tex(name) + " & " + " & ".join(sv(S[v].get(k)) for v, _ in V) + r" \\")
T += [r"\bottomrule", r"\end{tabular}"]
(OUT / "sensitivity.tex").write_text("\n".join(T) + "\n", encoding="utf-8")
print("sensitivity.tex", len(LAB), "rows; rejected at final pass:", len(S["rejected_at_final_pass"]))
