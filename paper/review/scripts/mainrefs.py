"""Write mainrefs.tex from main.aux so that supplement.tex can cite the numbers of main.tex labels.

Usage (from paper/review): latexmk -pdf main.tex ; python scripts/mainrefs.py ; latexmk -pdf supplement.tex
Each \\newlabel{key}{{number}{page}...} of main.aux becomes \\csname mr@key\\endcsname -> number.
"""
import os
import re

here = os.path.dirname(os.path.abspath(__file__))
root = os.path.dirname(here)
aux = open(os.path.join(root, 'main.aux'), encoding='utf-8').read()
out = ['% generated by scripts/mainrefs.py from main.aux; do not edit']
for key, num in re.findall(r'\\newlabel\{([^}]+)\}\{\{([^}]*)\}', aux):
    if key.startswith('@') or '@' in key:
        continue
    out.append('\\expandafter\\gdef\\csname mr@%s\\endcsname{%s}' % (key, num))
open(os.path.join(root, 'mainrefs.tex'), 'w', encoding='utf-8').write('\n'.join(out) + '\n')
print(len(out) - 1, 'labels written')
