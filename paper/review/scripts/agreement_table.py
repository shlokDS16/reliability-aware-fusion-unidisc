"""Supplement S4: agreement of the two extractors on the eight double-read studies (D0054 second-reader ids).

Reads analysis/extraction/d0052/agreement-8-texts/agreement-stage-a.json (agreement.py 1.0.2, stage-a mode, --texts),
per-record-stage-a.csv, and the D0060 block of rq-results.json (factor type, claim status, QA item scores, study-level
flags); writes paper/review/tables/extraction-agreement.tex (pooled measures) and extraction-agreement-records.tex
(per study). agreement.py stores an F1 measure as [2 x matched, n_A + n_B]; the tables print the matched count, the
number both extractors listed together, the union (n_A + n_B - matched) and F1 (gate audit 2026-10-21 finding 3).
Nothing is typed by hand.

    python paper/review/scripts/agreement_table.py
"""
import csv
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
A = ROOT / "analysis/extraction/d0052/agreement-8-texts"
OUT = ROOT / "paper/review/tables"
m = json.load(open(A / "agreement-stage-a.json", encoding="utf-8"))["metrics"]
X = json.load(open(ROOT / "analysis/extraction/d0052/rq-results.json", encoding="utf-8"))["D0060"]["agreement_extra"]
RATIO = [("G1 accept EA", "Entries of extractor A accepted by the validator"),
         ("G1 accept EB", "Entries of extractor B accepted by the validator"),
         ("G3 raw S", "Study fields, raw agreement"),
         ("G3 raw D", "Design fields, raw agreement"),
         ("G3 raw F", "Census fields, raw agreement"),
         ("G3 raw QA-sub", "Appraisal sub-items, raw agreement"),
         ("G4 M-val", "Values of contrast units both found"),
         ("G4 M-sign", "Metric direction of contrast units both found"),
         ("G4 M-class", "Factor type of matched comparison groups"),
         ("G4 M-anchorG", "Anchor arm of matched comparison groups")]
F1 = [("G4 F1_G", "Comparison groups"), ("G4 F1_K", "Contrast units"), ("G4 F1_H", "Headline-number units")]


def f(x, d=2):
    return "--" if x is None else f"{x:.{d}f}"


L = [r"% generated by paper/review/scripts/agreement_table.py from analysis/extraction/d0052/agreement-8-texts and rq-results.json; do not edit",
     r"\begin{tabular}{@{}l r r r@{}}", r"\toprule", r"Measure & Agreed & Compared & Share \\", r"\midrule"]
for k, name in RATIO:
    e = m[k]
    L.append(f"{name} & {e['numerator']:.0f} & {e['denominator']:.0f} & {f(e.get('point'))} \\\\")
qa = X["qa_item_scores_low"]
L.append(f"QA item scores (low reading), 8 studies x 9 items & {qa['agree']} & {qa['of']} & {f(qa['agree'] / qa['of'])} \\\\")
fl = X["study_level_flags_total"]
L.append(f"Study-level flags behind the verdicts (14 flags) & {fl['agree']} & {fl['of']} & {f(fl['agree'] / fl['of'])} \\\\")
cs = X["claim_status"]
L.append(f"Claim status of matched claims, Cohen's $\\kappa$ & \\multicolumn{{2}}{{r}}{{{cs['pairs']} pairs}} & {f(cs['kappa'])} \\\\")
L += [r"\midrule", r"Item found by both & Matched & Listed (A + B) & Union, F1 \\", r"\midrule"]
for k, name in F1:
    e = m[k]
    matched = e["numerator"] / 2
    union = e["denominator"] - matched
    L.append(f"{name} & {matched:.0f} & {e['denominator']:.0f} & {union:.0f}, {f(e.get('point'))} \\\\")
L += [r"\bottomrule", r"\end{tabular}"]
(OUT / "extraction-agreement.tex").write_text("\n".join(L) + "\n", encoding="utf-8")

per = {}
for r in csv.DictReader(open(A / "per-record-stage-a.csv", encoding="utf-8")):
    if r["metric"] in ("G4 F1_G", "G4 F1_K", "G1 accept EA", "G1 accept EB"):
        per.setdefault((r["id"], r["stratum"]), {})[r["metric"]] = (float(r["numerator"]), float(r["denominator"]))
P = [r"% generated by paper/review/scripts/agreement_table.py; do not edit", r"\begin{tabular}{@{}l l r r r r@{}}",
     r"\toprule", r"Study & Stratum & Groups matched / union & Units matched / union & Accepted A & Accepted B \\", r"\midrule"]


def mu(d, k):
    if k not in d or d[k][1] == 0:
        return "--"
    mt = d[k][0] / 2
    return f"{mt:.0f}/{d[k][1] - mt:.0f}"


for (i, h), d in sorted(per.items(), key=lambda x: (x[0][1], x[0][0])):
    c = lambda k: "--" if k not in d or d[k][1] == 0 else f"{d[k][0]:.0f}/{d[k][1]:.0f}"
    P.append(f"{i} & {h} & {mu(d, 'G4 F1_G')} & {mu(d, 'G4 F1_K')} & {c('G1 accept EA')} & {c('G1 accept EB')} \\\\")
P += [r"\bottomrule", r"\end{tabular}"]
(OUT / "extraction-agreement-records.tex").write_text("\n".join(P) + "\n", encoding="utf-8")
print("written", len(RATIO) + 3 + len(F1), "rows,", len(per), "studies")
