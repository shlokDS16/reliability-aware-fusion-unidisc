"""Supplement S4: agreement of the two extractors on the eight double-read studies (D0054 second-reader ids).

Reads analysis/extraction/d0052/agreement-8-texts/agreement-stage-a.json (agreement.py 1.0.2, stage-a mode, --texts)
and per-record-stage-a.csv; writes paper/review/tables/extraction-agreement.tex (pooled metrics) and
paper/review/tables/extraction-agreement-records.tex (per-study group and unit matching). Nothing is typed by hand.

    python paper/review/scripts/agreement_table.py
"""
import csv
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
A = ROOT / "analysis/extraction/d0052/agreement-8-texts"
OUT = ROOT / "paper/review/tables"
m = json.load(open(A / "agreement-stage-a.json", encoding="utf-8"))["metrics"]
ROWS = [("G1 accept EA", "Entries of extractor A accepted by the validator"),
        ("G1 accept EB", "Entries of extractor B accepted by the validator"),
        ("G3 raw S", "Study fields (S block), raw agreement"),
        ("G3 raw D", "Design fields (D block), raw agreement"),
        ("G3 raw F", "Census fields (F block), raw agreement"),
        ("G3 raw QA-sub", "Appraisal sub-items, raw agreement"),
        ("G3 K-attr", "Group attributes (budget, held fixed, scoring, credited ablation)"),
        ("G4 F1_G", "Comparison groups found by both (F1)"),
        ("G4 F1_K", "Contrast units found by both (F1)"),
        ("G4 F1_H", "Headline-number units found by both (F1)"),
        ("G4 M-val", "Values of units found by both"),
        ("G4 M-sign", "Metric direction of units found by both"),
        ("G4 M-class", "Factor type of matched groups"),
        ("G4 M-anchorG", "Anchor arm of matched groups")]


def f(x, d=3):
    return "--" if x is None else f"{x:.{d}f}"


L = [r"% generated by paper/review/scripts/agreement_table.py from analysis/extraction/d0052/agreement-8-texts; do not edit",
     r"\begin{tabular}{@{}l r r r@{}}", r"\toprule", r"Measure & Agreed / compared & Share & Lower bound \\", r"\midrule"]
for k, name in ROWS:
    e = m[k]
    nd = (f"{e['numerator']:.0f} / {e['denominator']:.0f}" if e.get("denominator") is not None else "--")
    L.append(f"{name} & {nd} & {f(e.get('point'))} & {f(e.get('LB90'))} \\\\")
L += [r"\bottomrule", r"\end{tabular}"]
(OUT / "extraction-agreement.tex").write_text("\n".join(L) + "\n", encoding="utf-8")

per = {}
for r in csv.DictReader(open(A / "per-record-stage-a.csv", encoding="utf-8")):
    if r["metric"] in ("G4 F1_G", "G4 F1_K", "G1 accept EA", "G1 accept EB"):
        per.setdefault((r["id"], r["stratum"]), {})[r["metric"]] = (float(r["numerator"]), float(r["denominator"]))
P = [r"% generated by paper/review/scripts/agreement_table.py; do not edit", r"\begin{tabular}{@{}l l r r r r@{}}",
     r"\toprule", r"Study & Stratum & Groups (F1) & Units (F1) & Accepted A & Accepted B \\", r"\midrule"]
for (i, h), d in sorted(per.items(), key=lambda x: (x[0][1], x[0][0])):
    c = lambda k: "--" if k not in d or d[k][1] == 0 else f"{d[k][0]:.0f}/{d[k][1]:.0f}"
    P.append(f"{i} & {h} & {c('G4 F1_G')} & {c('G4 F1_K')} & {c('G1 accept EA')} & {c('G1 accept EB')} \\\\")
P += [r"\bottomrule", r"\end{tabular}"]
(OUT / "extraction-agreement-records.tex").write_text("\n".join(P) + "\n", encoding="utf-8")
print("written", len(ROWS), "metrics,", len(per), "studies")
