"""Revision 2026-10-21 tables (assessment: practitioner synthesis, Q6).

1. tables/exemplars.tex: canonical models mapped onto the five choices, rows copied from the generated
   condensed design-space table (tables/design-space-condensed.tex), so no cell is retyped.
2. tables/partial-fits.tex: the 11 partial fits with row provenance (copied from an earlier reading or read at
   section level), evidence level and what the notation is missing, from research/review/coverage/design-space-v1.csv.

    python paper/review/scripts/revision_tables.py   (from the repository root)
"""
import csv
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
T = ROOT / "paper/review/tables"
EXEMPLARS = ["MDLM", "SEDD", "LLaDA", "Dream 7B", "Fast-dLLM", "BD3-LM", "ReMDM", "Duo", "Plaid",
             "MMaDA", "UniDisc", "Show-o2"]
rows = {}
for line in (T / "design-space-condensed.tex").read_text(encoding="utf-8").splitlines():
    cells = [c.strip() for c in line.rstrip("\\ ").split("&")]
    if len(cells) == 8:
        name = re.sub(r"~?\\cite\{[^}]*\}", "", cells[1]).strip()
        rows[name] = cells
missing = [m for m in EXEMPLARS if m not in rows]
if missing:
    raise SystemExit(f"not in condensed table: {missing}")
out = [r"% generated by paper/review/scripts/revision_tables.py from tables/design-space-condensed.tex; do not edit"]
for m in EXEMPLARS:
    i, model, c1, pos, val, rev, lev, fit = rows[m]
    out.append(" & ".join([model, c1, pos, val, rev, fit]) + r" \\")
(T / "exemplars.tex").write_text("\n".join(out) + "\n", encoding="utf-8")


def tex(s):
    s = s.replace("\\", "/").replace("&", r"\&").replace("%", r"\%").replace("_", r"\_").replace("#", r"\#")
    s = s.replace("$", r"\$").replace("{", r"\{").replace("}", r"\}").replace("^", r"\^{}").replace("~", r"\~{}")
    return " ".join(s.split())


D = list(csv.DictReader(open(ROOT / "research/review/coverage/design-space-v1.csv", encoding="utf-8")))
P = [d for d in D if d["fits (yes/partly/no)"].strip().lower().startswith("part")]
out = [r"% generated by paper/review/scripts/revision_tables.py from research/review/coverage/design-space-v1.csv; do not edit"]
for d in P:
    n = int(d["id"][1:])
    prov = "copied" if n <= 29 else "read"
    ev = d["evidence level"].split()[0] if d["evidence level"].strip() else "--"
    out.append(" & ".join([d["id"], tex(d["name"]), prov, tex(ev), tex(d["what is missing"])]) + r" \\")
(T / "partial-fits.tex").write_text("\n".join(out) + "\n", encoding="utf-8")
print("exemplars", len(EXEMPLARS), "partial fits", len(P), "copied", sum(int(d['id'][1:]) <= 29 for d in P))
