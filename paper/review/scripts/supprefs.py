"""Supplement table numbers for the main text: reads paper/review/supplement.aux and writes paper/review/supprefs.tex
with \\suppTabScreen, \\suppTabGap and \\suppTabDesign (the counterpart of mainrefs.py, which goes the other way).
Build order: latexmk main.tex; python scripts/mainrefs.py; latexmk supplement.tex; python scripts/supprefs.py; latexmk main.tex.

    python -I paper/review/scripts/supprefs.py
"""
import re
from pathlib import Path

D = Path(__file__).resolve().parents[1]
aux = (D / "supplement.aux").read_text(encoding="latin-1")
num = dict(re.findall(r"\\newlabel\{((?:tab|fig):[^}]*)\}\{\{(S\d+)\}", aux))
MAP = {"suppTabScreen": "tab:screening", "suppTabGap": "tab:census-gap", "suppTabDesign": "tab:design",
       "suppTabLandmark": "tab:landmark", "suppTabExp": "tab:exp003-arms", "suppTabLevers": "tab:levers",
       "suppFigFormalism": "fig:formalism", "suppFigDots": "fig:taxonomy", "suppFigTree": "fig:tree"}
lines = ["% generated by scripts/supprefs.py from supplement.aux; do not edit"]
for cmd, lab in MAP.items():
    lines.append(f"\\newcommand{{\\{cmd}}}{{{'Figure' if lab.startswith('fig:') else 'Table'}~{num[lab]}}}")
(D / "supprefs.tex").write_text("\n".join(lines) + "\n", encoding="utf-8")
print({c: num[l] for c, l in MAP.items()})
