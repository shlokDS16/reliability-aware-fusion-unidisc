"""Taxonomy tree of the 47 design-space models (introduction figure), grouped by the "family" column of
research/review/coverage/design-space-v1.csv. Writes paper/review/tables/taxonomy-tree.tex (a forest tree; every
leaf cites the model's arXiv record). The grouping of families into branches is fixed below; every family in the CSV
must be placed exactly once, and every model appears once.

    python -E -P paper/review/scripts/fig_taxonomy.py
"""
import csv
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
rows = list(csv.DictReader(open(ROOT / "research/review/coverage/design-space-v1.csv", encoding="utf-8")))

TREE = [
    ("Discrete state space", [
        ("General corruption", ["general discrete (Markov matrices)", "general discrete (CTMC)", "general discrete (CTMC, score)"]),
        ("Absorbing (masked)", ["absorbing", "absorbing (sampler analysis)", "absorbing (order-agnostic AR)"]),
        ("Uniform", ["uniform", "uniform (with auxiliary simplex latent)"]),
        ("Block, semi-autoregressive", ["block (semi-AR)"]),
        ("Adapted from autoregressive", ["AR-adapted absorbing", "AR-adapted absorbing (RL)", "AR-adapted absorbing + edit channel"]),
        ("Flow and hybrid channels", ["flow (probability path)", "hybrid channel (erasure + Gaussian)"]),
    ]),
    ("Continuous state space", [
        ("Gaussian on embeddings", ["Gaussian/embedding", "Gaussian/embedding (conditional seq2seq)"]),
        ("Logit simplex", ["Gaussian/embedding (logit simplex)", "Gaussian/embedding (logit simplex), AR-adapted",
                           "Gaussian/embedding (logit simplex, block)"]),
    ]),
    ("Samplers and distillation", [
        ("Order and remasking", ["sampler-only (image VQ tokens)", "sampler-only (remasking)", "sampler-only (adaptive k)"]),
        ("Cache and joint draws", ["sampler-only (cache and adaptive k)", "sampler-only (joint draw)", "distillation (joint over positions)"]),
    ]),
    ("Unified multimodal", [
        ("Discrete diffusion", ["unified multimodal (discrete)", "unified multimodal (discrete, omnimodal)"]),
        ("Understanding", ["unified multimodal (understanding only)", "unified multimodal (understanding, AR-adapted)"]),
        ("Flow and dual diffusion", ["flow (unified, metric path)", "unified multimodal (flow image + masked text)"]),
        ("Autoregressive text, diffusion image", ["hybrid AR+diffusion (unified)", "hybrid AR+diffusion (continuous image)"]),
    ]),
]

placed = [f for _, subs in TREE for _, fams in subs for f in fams]
fams_csv = {r["family"] for r in rows}
assert sorted(placed) == sorted(set(placed)) and set(placed) == fams_csv, (set(placed) ^ fams_csv)


def short(name):
    for a, b in (("Zheng et al. (time-agnostic, first-hitting)", "Zheng et al."), ("Campbell et al. (CTMC)", "Campbell et al."),
                 ("DFM (discrete flow matching)", "DFM"), ("UDLM (Schiff et al., guidance)", "UDLM"),
                 ("Simplax (Simplex Relaxation)", "Simplax"), ("Discrete Copula Diffusion (DCD)", "DCD"),
                 ("D-DiT (Dual Diffusion)", "D-DiT")):
        if name == a:
            return b
    return name


def leaf(fams):
    ms = [r for r in rows if r["family"] in fams]
    items = [f"{short(r['name'])}~\\cite{{arXiv:{r['arXiv ID'].strip()}}}" for r in ms]
    lines = [", ".join(items[j:j + 3]) for j in range(0, len(items), 3)]   # forest does not wrap: 3 models per line
    return ",\\\\ ".join(lines), len(ms)


BREAK = {"Discrete state space": "Discrete\\\\state space", "Continuous state space": "Continuous\\\\state space",
         "Samplers and distillation": "Samplers and\\\\distillation", "Unified multimodal": "Unified\\\\multimodal",
         "Block, semi-autoregressive": "Block, semi-\\\\autoregressive", "Adapted from autoregressive": "Adapted from\\\\autoregressive",
         "Flow and hybrid channels": "Flow and\\\\hybrid channels", "Autoregressive text, diffusion image": "Autoregressive text,\\\\diffusion image",
         "Flow and dual diffusion": "Flow and dual\\\\diffusion"}


L = ["% generated by paper/review/scripts/fig_taxonomy.py from research/review/coverage/design-space-v1.csv; do not edit",
     r"\begin{forest}",
     r"for tree={grow'=east, parent anchor=east, child anchor=west, anchor=west, draw, rounded corners=1pt,"
     r" font=\scriptsize, inner sep=1.5pt, s sep=1pt, l sep=6pt, edge={draw=black!50}, edge path={\noexpand\path[\forestoption{edge}]"
     r" (!u.parent anchor) -- +(3pt,0) |- (.child anchor)\forestoption{edge label};}},",
     r"[{Design space\\(47 models)}, text width=1.3cm, align=center"]
n = 0
O1, O2, O3 = "align=left, fill=black!8", "align=left", "align=left, draw=none"
for top, subs in TREE:
    L.append(f"  [{{{BREAK.get(top, top)}}}, {O1}")
    for name, fams in subs:
        t, k = leaf(fams)
        n += k
        L.append(f"    [{{{BREAK.get(name, name)}}}, {O2} [{{{t}}}, {O3}]]")
    L.append("  ]")
L += ["]", r"\end{forest}"]
assert n == len(rows) == 47, n
(ROOT / "paper/review/tables/taxonomy-tree.tex").write_text("\n".join(L) + "\n", encoding="utf-8")
print("models", n, "branches", sum(len(s) for _, s in TREE))
